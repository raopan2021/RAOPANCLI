import path from 'node:path'
import fs from 'fs-extra'
import { print, printError, printSuccess } from '../utils/print.js'

// 遍历目录，删除其中所有 node_modules 文件夹
function searchNodeModules(dir) {
  try {
    if (!fs.pathExistsSync(dir))
      return
    for (const file of fs.readdirSync(dir)) {
      const curPath = path.join(dir, file)
      const stats = fs.lstatSync(curPath)
      if (!stats.isDirectory())
        continue
      if (file === 'node_modules') {
        try {
          // 使用原生递归删除，跨平台且速度快
          fs.rmSync(curPath, { recursive: true, force: true })
          printSuccess(`删除成功 ${curPath}`)
        }
        catch {
          printError(`删除文件夹失败 ${curPath}`)
        }
      }
      else {
        searchNodeModules(curPath)
      }
    }
  }
  catch {
    printError(`遍历文件夹失败 ${dir}`)
  }
}

function deleteNodeModules() {
  searchNodeModules(process.cwd())
  print('删除成功')
}

export default deleteNodeModules
